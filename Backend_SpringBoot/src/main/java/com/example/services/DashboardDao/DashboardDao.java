package com.example.services.DashboardDao;

import com.example.dto.dashboard.DashboardDto;
import com.example.exception.ResourceNotFoundException;
import com.example.services.DbTime;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.util.List;

@Service
public class DashboardDao {

    // The only statuses a record can have
    public static final List<String> ALLOWED_STATUSES = List.of("Requested", "Accepted", "Removed", "Rejected");

    @Autowired
    private JdbcTemplate jdbcTemplate;

    // Reusable RowMapper: database row (snake_case columns) -> DTO
    private final RowMapper<DashboardDto> dashboardMapper = (rs, rowNum) -> {
        DashboardDto dto = new DashboardDto();
        dto.setId(rs.getLong("id"));

        dto.setDashboardName(rs.getString("dashboard_name"));
        dto.setRequestedBy(rs.getString("requested_by"));
        dto.setDevelopedBy(rs.getString("developed_by"));
        dto.setCompletedDate(DbTime.parseDate(rs.getString("completed_date")));
        dto.setTeamName(rs.getString("team_name"));
        dto.setTeamManager(rs.getString("team_manager"));
        dto.setDataSourceName(rs.getString("data_source_name"));
        dto.setCustomQueryFlag(rs.getString("custom_query_flag"));
        dto.setQueryText(rs.getString("query_text"));
        dto.setSharedDataSource(rs.getString("shared_data_source"));
        dto.setConnectionMode(rs.getString("connection_mode"));
        dto.setRefreshRate(rs.getString("refresh_rate"));
        dto.setConnectionUserDB(rs.getString("connection_user_db"));
        dto.setMenuName(rs.getString("menu_name"));
        dto.setMenuGroupName(rs.getString("menu_group_name"));
        dto.setMenuEntryName(rs.getString("menu_entry_name"));
        dto.setAccessRoles(rs.getString("access_roles"));
        dto.setWorkspaceName(rs.getString("workspace_name"));
        dto.setFolderName(rs.getString("folder_name"));
        dto.setPublishedReportName(rs.getString("published_report_name"));
        dto.setReportUrl(rs.getString("report_url"));
        dto.setCalculatedFields(rs.getString("calculated_fields"));
        dto.setSubmittedAt(DbTime.parseInstant(rs.getString("submitted_at")));
        dto.setCurrentStatus(rs.getString("current_status"));
        dto.setUpdateStatus(DbTime.parseInstant(rs.getString("update_status")));
//        dto.setAdminName(rs.getString("admin_name"));
        return dto;
    };

    // Insert a new record.
    // The id is generated by the database (INTEGER PRIMARY KEY AUTOINCREMENT) and read back with
    // last_insert_rowid(). Inside this transaction both statements use the same connection,
    // so the id is always the one of OUR insert.
    @Transactional
    public DashboardDto insertSaveData(DashboardDto dto) {

        // Lifecycle fields are decided by the server, not by the client
        Instant now = Instant.now();
        dto.setCurrentStatus("Requested");
        dto.setSubmittedAt(now);
        dto.setUpdateStatus(now);

        String sqlInsert =
                "INSERT INTO dashboards (" +
                        "dashboard_name, requested_by, developed_by, completed_date, team_name, team_manager, " +
                        "data_source_name, custom_query_flag, query_text, shared_data_source, connection_mode, " +
                        "refresh_rate, connection_user_db, menu_name, menu_group_name, menu_entry_name, " +
                        "access_roles, workspace_name, folder_name, published_report_name, " +
                        "report_url, calculated_fields, submitted_at, current_status, update_status)" +
                        " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        jdbcTemplate.update(
                sqlInsert,
                dto.getDashboardName(),
                dto.getRequestedBy(),
                dto.getDevelopedBy(),
                DbTime.format(dto.getCompletedDate()),
                dto.getTeamName(),
                dto.getTeamManager(),
                dto.getDataSourceName(),
                dto.getCustomQueryFlag(),
                dto.getQueryText(),
                dto.getSharedDataSource(),
                dto.getConnectionMode(),
                dto.getRefreshRate(),
                dto.getConnectionUserDB(),
                dto.getMenuName(),
                dto.getMenuGroupName(),
                dto.getMenuEntryName(),
                dto.getAccessRoles(),
                dto.getWorkspaceName(),
                dto.getFolderName(),
                dto.getPublishedReportName(),
                dto.getReportUrl(),
                dto.getCalculatedFields(),
                DbTime.format(dto.getSubmittedAt()),
                dto.getCurrentStatus(),
                DbTime.format(dto.getUpdateStatus())
        );

        Long newId = jdbcTemplate.queryForObject("SELECT last_insert_rowid()", Long.class);

        // Read back exactly the row we inserted
        return getById(newId);
    }

    // Get all records, newest first
    public List<DashboardDto> getAllMainData() {
        return jdbcTemplate.query("SELECT * FROM dashboards ORDER BY submitted_at DESC, id DESC", dashboardMapper);
    }

    // Get by ID (null if it does not exist)
    public DashboardDto getById(Long id) {
        List<DashboardDto> list = jdbcTemplate.query("SELECT * FROM dashboards WHERE id = ?", dashboardMapper, id);
        return list.isEmpty() ? null : list.get(0);
    }

    // Change the status of a record and write an audit row, in one transaction.
    // Throws IllegalArgumentException (400) for an invalid/unchanged status and
    // ResourceNotFoundException (404) when the id does not exist.
    @Transactional
    public DashboardDto updateStatusAndAudit(Long id, String newStatus/*, String username*/) {

        if (!ALLOWED_STATUSES.contains(newStatus)) {
            throw new IllegalArgumentException("Invalid status '" + newStatus + "'. Allowed: " + ALLOWED_STATUSES);
        }

        List<String> current = jdbcTemplate.queryForList(
                "SELECT current_status FROM dashboards WHERE id = ?", String.class, id);
        if (current.isEmpty()) {
            throw new ResourceNotFoundException("Record with id " + id + " not found");
        }
        String previousStatus = current.get(0);

        if (newStatus.equals(previousStatus)) {
            throw new IllegalArgumentException("Record " + id + " already has status '" + newStatus + "'");
        }

        String now = DbTime.format(Instant.now());

        jdbcTemplate.update(
                "UPDATE dashboards SET current_status = ?, update_status = ? WHERE id = ?",
                newStatus, now, id
        );

        // audit_id is generated by the database (AUTOINCREMENT)
        jdbcTemplate.update(
                // insert and "changed_by"
                "INSERT INTO dashboard_audit (dashboard_id, previous_status, new_status, change_timestamp) VALUES (?, ?, ?, ?)",
                id,
//                  username,
                previousStatus,
                newStatus,
                now
        );

        return getById(id);
    }
}
