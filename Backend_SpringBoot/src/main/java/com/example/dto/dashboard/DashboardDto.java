package com.example.dto.dashboard;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonProperty;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.Instant;
import java.time.LocalDate;

// One registered dashboard / report (table "dashboards")
@Data
@AllArgsConstructor
@NoArgsConstructor
public class DashboardDto {

    // Generated by the database (AUTOINCREMENT)
    @JsonProperty("id")
    private Long id;

    // --- General information ---
    @NotBlank
    @JsonProperty("dashboardName")
    private String dashboardName;
    @NotBlank
    @JsonProperty("requestedBy")
    private String requestedBy;
    @NotBlank
    @JsonProperty("developedBy")
    private String developedBy;

    @NotNull
    @JsonProperty("completedDate")
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
    private LocalDate completedDate;

    // --- Team information ---
    @NotBlank
    @JsonProperty("teamName")
    private String teamName;
    @NotBlank
    @JsonProperty("teamManager")
    private String teamManager;

    // --- Data information ---
    // queryText / refreshRate may be empty ("") when not applicable, see the @AssertTrue checks below
    @NotBlank
    @JsonProperty("dataSourceName")
    private String dataSourceName;
    @NotBlank
    @Pattern(regexp = "Yes|No")
    @JsonProperty("customQueryFlag")
    private String customQueryFlag;
    @NotNull
    @JsonProperty("queryText")
    private String queryText;
    @NotBlank
    @Pattern(regexp = "Yes|No")
    @JsonProperty("sharedDataSource")
    private String sharedDataSource;
    @NotBlank
    @Pattern(regexp = "Live|Scheduled")
    @JsonProperty("connectionMode")
    private String connectionMode;
    @NotNull
    @JsonProperty("refreshRate")
    private String refreshRate;
    @NotBlank
    @JsonProperty("connectionUserDB")
    private String connectionUserDB;

    // --- Portal menu information ---
    @NotBlank
    @JsonProperty("menuName")
    private String menuName;
    @NotBlank
    @JsonProperty("menuGroupName")
    private String menuGroupName;
    @NotBlank
    @JsonProperty("menuEntryName")
    private String menuEntryName;
    @NotBlank
    @JsonProperty("accessRoles")
    private String accessRoles;

    // --- Publishing information ---
    @NotBlank
    @JsonProperty("workspaceName")
    private String workspaceName;
    @NotBlank
    @JsonProperty("folderName")
    private String folderName;
    @NotBlank
    @JsonProperty("publishedReportName")
    private String publishedReportName;
    @NotBlank
    @JsonProperty("reportUrl")
    private String reportUrl;

    // --- Calculated fields ---
    @NotBlank
    @JsonProperty("calculatedFields")
    private String calculatedFields;

    // --- Lifecycle (set by the server, values sent by the client are ignored) ---
    @JsonProperty("submittedAt")
    private Instant submittedAt;

    @JsonProperty("currentStatus")
    private String currentStatus;

    // Time of the last status change
    @JsonProperty("updateStatus")
    private Instant updateStatus;

/*    @NotNull
    @JsonProperty("adminName")
    private String adminName; */

    // --- Conditional checks (same rules as the frontend Validation.js) ---

    // If a custom query is used, the query text is required
    @JsonIgnore
    @AssertTrue(message = "queryText is required when customQueryFlag is Yes")
    public boolean isQueryTextValid() {
        return !"Yes".equals(customQueryFlag) || (queryText != null && !queryText.isBlank());
    }

    // If the data is refreshed on a schedule, the refresh rate is required
    @JsonIgnore
    @AssertTrue(message = "refreshRate is required when connectionMode is Scheduled")
    public boolean isRefreshRateValid() {
        return !"Scheduled".equals(connectionMode) || (refreshRate != null && !refreshRate.isBlank());
    }
}
